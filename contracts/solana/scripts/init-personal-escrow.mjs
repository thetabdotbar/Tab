// One-shot init for the Personal Escrow program.
// Calls `initialize(fee_bps=0)` to create the EscrowConfig PDA, then
// `add_executor(executor_pubkey)` so the bot's executor wallet can
// release escrows. Same deployer wallet as every other init script —
// `~/.config/solana/tab-deployer.json`.
//
// Run from ./, AFTER:
//   1. ./scripts/setup-personal-escrow.sh  (generates keypair, syncs IDs, builds)
//   2. anchor deploy --program-name tab_escrow_personal --provider.cluster mainnet
//
// Usage:
//   node scripts/init-personal-escrow.mjs
//
// Idempotent: if the EscrowConfig PDA already exists, the initialize
// instruction reverts cleanly. Same for the executor entry — re-running
// after a partial first run is safe.

import {
  Connection,
  Keypair,
  PublicKey,
  SystemProgram,
  Transaction,
  TransactionInstruction,
} from "@solana/web3.js";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";

// ---- config — matches setup-mainnet.ts / init-personal-sub.mjs ----

// Read the program ID from the keypair generated by setup-personal-escrow.sh
// rather than hardcoding, so this script keeps working when you regenerate
// the keypair on a new machine.
const PROGRAM_KEYPAIR_PATH = "target/deploy/tab_escrow_personal-keypair.json";
const PROGRAM_ID = (() => {
  const bytes = JSON.parse(fs.readFileSync(PROGRAM_KEYPAIR_PATH, "utf8"));
  return Keypair.fromSecretKey(Uint8Array.from(bytes)).publicKey;
})();

const USDC_MINT = new PublicKey(
  "EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v"
);
// Same fee recipient as the business escrow program (kept consistent
// so admin can never accidentally route to a fresh address if they
// ever flip the fee — though MAX_FEE_BPS=0 in the personal program
// makes that impossible by design).
const FEE_RECIPIENT = new PublicKey(
  "552531jSitQndRiiQK89ZshxvvRbEzSekQoniWpjSBr"
);
// The bot's executor on Solana. Matches the existing tab-bot executor —
// same wallet, same signer, just registered on the new program too.
const EXECUTOR_PUBKEY = new PublicKey(
  process.env.SOLANA_EXECUTOR_PUBKEY ??
    // If you don't set the env, this falls back to reading the pubkey
    // from the deployer wallet (single-wallet ops). Override via env
    // when you want the executor to be a separate wallet.
    loadKeypair("~/.config/solana/tab-deployer.json").publicKey.toBase58()
);

const RPC_URL = process.env.SOLANA_RPC_URL ?? "https://api.mainnet-beta.solana.com";

// ---- helpers ----

function loadKeypair(p) {
  const expanded = p.startsWith("~") ? path.join(os.homedir(), p.slice(1)) : p;
  const bytes = JSON.parse(fs.readFileSync(expanded, "utf8"));
  return Keypair.fromSecretKey(Uint8Array.from(bytes));
}

function anchorDiscriminator(name) {
  return crypto.createHash("sha256").update(`global:${name}`).digest().slice(0, 8);
}

function u64LE(n) {
  const b = Buffer.alloc(8);
  b.writeBigUInt64LE(BigInt(n));
  return b;
}

async function send(conn, ix, admin, label) {
  const tx = new Transaction().add(ix);
  tx.feePayer = admin.publicKey;
  const { blockhash, lastValidBlockHeight } = await conn.getLatestBlockhash(
    "confirmed"
  );
  tx.recentBlockhash = blockhash;
  tx.sign(admin);
  console.log(`Submitting ${label}…`);
  try {
    const sig = await conn.sendRawTransaction(tx.serialize(), {
      skipPreflight: false,
      preflightCommitment: "confirmed",
    });
    console.log(`  signature: ${sig}`);
    await conn.confirmTransaction(
      { signature: sig, blockhash, lastValidBlockHeight },
      "confirmed"
    );
    console.log(`  ✓ ${label} confirmed`);
    return sig;
  } catch (e) {
    const msg = e?.message ?? String(e);
    if (
      msg.includes("already in use") ||
      msg.includes("custom program error: 0x0")
    ) {
      console.log(`  ↪ ${label} already done (idempotent) — skipping`);
      return null;
    }
    throw e;
  }
}

// ---- main ----

async function main() {
  const admin = loadKeypair("~/.config/solana/tab-deployer.json");
  console.log("Admin (deployer):", admin.publicKey.toBase58());
  console.log("Program ID:      ", PROGRAM_ID.toBase58());
  console.log("Mint:            ", USDC_MINT.toBase58());
  console.log("Fee recipient:   ", FEE_RECIPIENT.toBase58());
  console.log("Executor:        ", EXECUTOR_PUBKEY.toBase58());
  console.log("RPC:             ", RPC_URL);
  console.log("");

  const conn = new Connection(RPC_URL, "confirmed");

  // 1. initialize(fee_bps=0)
  const [configPda, configBump] = PublicKey.findProgramAddressSync(
    [Buffer.from("escrow_config")],
    PROGRAM_ID
  );
  console.log("Escrow config PDA:", configPda.toBase58(), "bump:", configBump);
  const initData = Buffer.concat([anchorDiscriminator("initialize"), u64LE(0)]);
  const initIx = new TransactionInstruction({
    programId: PROGRAM_ID,
    data: initData,
    keys: [
      { pubkey: configPda, isSigner: false, isWritable: true },
      { pubkey: USDC_MINT, isSigner: false, isWritable: false },
      { pubkey: FEE_RECIPIENT, isSigner: false, isWritable: false },
      { pubkey: admin.publicKey, isSigner: true, isWritable: true },
      { pubkey: SystemProgram.programId, isSigner: false, isWritable: false },
    ],
  });
  await send(conn, initIx, admin, "initialize(fee_bps=0)");

  // 2. add_executor(executor_pubkey)
  const [executorPda, executorBump] = PublicKey.findProgramAddressSync(
    [Buffer.from("executor"), EXECUTOR_PUBKEY.toBuffer()],
    PROGRAM_ID
  );
  console.log("Executor PDA:", executorPda.toBase58(), "bump:", executorBump);
  const addExecData = Buffer.concat([
    anchorDiscriminator("add_executor"),
    EXECUTOR_PUBKEY.toBuffer(),
  ]);
  const addExecIx = new TransactionInstruction({
    programId: PROGRAM_ID,
    data: addExecData,
    keys: [
      { pubkey: configPda, isSigner: false, isWritable: false },
      { pubkey: executorPda, isSigner: false, isWritable: true },
      { pubkey: admin.publicKey, isSigner: true, isWritable: true },
      { pubkey: SystemProgram.programId, isSigner: false, isWritable: false },
    ],
  });
  await send(conn, addExecIx, admin, `add_executor(${EXECUTOR_PUBKEY.toBase58().slice(0, 8)}…)`);

  console.log("");
  console.log("=== Personal Escrow Program initialized ===");
  console.log("  Program ID:    ", PROGRAM_ID.toBase58());
  console.log("  Config PDA:    ", configPda.toBase58());
  console.log("  Executor PDA:  ", executorPda.toBase58());
  console.log("  Fee BPS:       0");
  console.log("");
  console.log("Final step — add to tab-web env (Vercel):");
  console.log(`  NEXT_PUBLIC_TAB_ESCROW_PERSONAL_SOLANA=${PROGRAM_ID.toBase58()}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
